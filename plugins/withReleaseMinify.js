const fs = require('node:fs');
const path = require('node:path');

const { withDangerousMod, withGradleProperties } = require('@expo/config-plugins');

const { setGradleProperty } = require('./gradleProperty');
const { PACKAGE, PROVIDERS } = require('./withHomeWidget');

/**
 * R8 (minify + resource shrinking) for Android release builds.
 *
 * Play's pre-launch report for 1.1.0 flagged the DEX as under-optimised: 3 %
 * obfuscated against a 25 % floor, with store visibility at stake from
 * February 2027. Expo leaves both switches off; the generated
 * `android/app/build.gradle` reads them from gradle.properties, and
 * `android/` is regenerated by `expo prebuild`, so — same as
 * withBuildArchitectures — this is the only place a value lasts.
 *
 * ── What the keep rules are for ───────────────────────────────────────────
 *
 * The libraries carry their own consumer rules (react-android, expo-modules-
 * core, RevenueCat, Play services, react-native-svg, expo-notifications), and
 * AAPT keeps every class the manifest names. What is left is what only this
 * app knows: names it looks up as strings.
 *
 * - The widget receivers. Launchers bind a placed widget to the receiver's
 *   class name, and HomeWidgetModule builds each ComponentName from a string
 *   ("$packageName.HomeWidgetProvider"). The manifest entry keeps the class,
 *   but a rename would orphan every widget already on a home screen, so the
 *   name is pinned here as well rather than left to AAPT's generated rules.
 * - expo-notifications. It ships `-keep class expo.modules.notifications.**`
 *   in its android/proguard-rules.pro, but its build.gradle never passes the
 *   file as consumerProguardFiles, so R8 never reads it. Without it R8 strips
 *   NotificationContent's private writeObject/readObject, every scheduled
 *   notification fails with NotSerializableException (found on the emulator:
 *   no rest-over alert, no reminders), and requests an older install stored
 *   in SharedPreferences are read back by their original class names.
 * - Java serialization hooks in general, which nothing calls by name.
 *
 * Every rule is a class R8 cannot obfuscate, and obfuscation is what Play
 * measures, so a rule goes in when a build shows it is needed, not in case.
 *
 * mapping.txt has to go to Play with every bundle, or crash stacks come back
 * as `a.b.c` — see docs/android-release-signing.md.
 */
const MINIFY_KEY = 'android.enableMinifyInReleaseBuilds';
const SHRINK_KEY = 'android.enableShrinkResourcesInReleaseBuilds';

const RULES_START = '# vinha-release-minify:start';
const RULES_END = '# vinha-release-minify:end';

// The widget plugin writes the Kotlin, so its package and receiver list are the
// ones to keep; a copy here would drift the day a widget is added.
const WIDGET_RECEIVERS = PROVIDERS.map((provider) => `${PACKAGE}.${provider.className}`);

const KEEP_RULES = [
  RULES_START,
  '# Written by plugins/withReleaseMinify.js; edits here are lost on prebuild.',
  '# Home-screen widget receivers: bound by class name on the launcher side and',
  '# looked up by string in HomeWidgetModule.',
  ...WIDGET_RECEIVERS.map((name) => `-keep class ${name} { *; }`),
  '# expo-notifications: its own rule, which its build.gradle never wires up.',
  '-keep class expo.modules.notifications.** { *; }',
  '# Java serialization hooks are found by name, never called.',
  '-keepclassmembers class * implements java.io.Serializable {',
  '    static final long serialVersionUID;',
  '    private static final java.io.ObjectStreamField[] serialPersistentFields;',
  '    private void writeObject(java.io.ObjectOutputStream);',
  '    private void readObject(java.io.ObjectInputStream);',
  '    private void readObjectNoData();',
  '    java.lang.Object writeReplace();',
  '    java.lang.Object readResolve();',
  '}',
  RULES_END,
].join('\n');

function applyReleaseMinify(properties) {
  setGradleProperty(properties, MINIFY_KEY, 'true');
  return setGradleProperty(properties, SHRINK_KEY, 'true');
}

/** Replaces this plugin's block, so a second prebuild does not stack a copy. */
function applyKeepRules(contents) {
  const start = contents.indexOf(RULES_START);
  const end = contents.indexOf(RULES_END);
  const without = start >= 0 && end > start ? contents.slice(0, start) + contents.slice(end + RULES_END.length) : contents;
  return `${without.trimEnd()}\n\n${KEEP_RULES}\n`;
}

module.exports = function withReleaseMinify(config) {
  config = withGradleProperties(config, (config) => {
    applyReleaseMinify(config.modResults);
    return config;
  });

  return withDangerousMod(config, [
    'android',
    (config) => {
      const file = path.join(config.modRequest.platformProjectRoot, 'app', 'proguard-rules.pro');
      const contents = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      fs.writeFileSync(file, applyKeepRules(contents));
      return config;
    },
  ]);
};

module.exports.applyReleaseMinify = applyReleaseMinify;
module.exports.applyKeepRules = applyKeepRules;
module.exports.MINIFY_KEY = MINIFY_KEY;
module.exports.SHRINK_KEY = SHRINK_KEY;
module.exports.WIDGET_RECEIVERS = WIDGET_RECEIVERS;
module.exports.KEEP_RULES = KEEP_RULES;
